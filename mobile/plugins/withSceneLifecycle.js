const fs = require('fs');
const path = require('path');
const { IOSConfig, withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');

/**
 * Adopts the UIScene life cycle on iOS.
 *
 * Apps linked against the iOS 27 SDK (Xcode 27) must use scenes: on iOS 27, UIKit stops an app
 * without a scene manifest at launch (EXC_BREAKPOINT in
 * _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption). The Expo SDK 55 template still
 * creates its window in AppDelegate, so this plugin
 *   1. declares a single-window scene manifest in Info.plist,
 *   2. adds SceneDelegate.swift, which creates the window, starts React Native and forwards
 *      scene events to the app delegate, and
 *   3. removes the window creation from AppDelegate.swift.
 * Expo SDK 56 and later ship their own scene delegate; drop this plugin when upgrading.
 */

const MARKER = '[companion] scene life cycle';
const SCENE_DELEGATE_FILE = 'SceneDelegate.swift';

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: 'Default Configuration',
        UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
      },
    ],
  },
};

const SCENE_DELEGATE_SOURCE = `// ${MARKER}: generated by plugins/withSceneLifecycle.js. Do not edit; change the plugin
// and run \`npx expo prebuild\` instead.
//
// Apps built with the iOS 27 SDK must adopt the UIScene life cycle. This scene delegate creates the
// window, starts React Native in it, and forwards scene events to the app delegate, which UIKit no
// longer calls for them.
internal import Expo
import React
import UIKit

class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate,
          let factory = appDelegate.reactNativeFactory else {
      return
    }
    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // A link that cold-starts the app arrives in the connection options; React Native's
    // Linking.getInitialURL() reads it from the launch options.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any]?
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions = [UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey"): url]
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  func sceneDidDisconnect(_ scene: UIScene) {
    window = nil
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = appDelegate?.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

// The Expo SDK 55 template's window setup in application(_:didFinishLaunchingWithOptions:).
const TEMPLATE_WINDOW_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\([^)]*\)\n#endif\n/;

function removeTemplateWindowSetup(appDelegate) {
  if (appDelegate.includes(MARKER)) {
    return appDelegate;
  }
  if (!TEMPLATE_WINDOW_BLOCK.test(appDelegate)) {
    throw new Error(
      'withSceneLifecycle: AppDelegate.swift does not match the Expo SDK 55 template. ' +
        'Update or remove plugins/withSceneLifecycle.js (Expo SDK 56+ adopts scenes itself).',
    );
  }
  return appDelegate.replace(
    TEMPLATE_WINDOW_BLOCK,
    `    // ${MARKER}: SceneDelegate creates the window and starts React Native.\n`,
  );
}

function withSceneManifest(config) {
  return withInfoPlist(config, (plistConfig) => {
    plistConfig.modResults.UIApplicationSceneManifest = SCENE_MANIFEST;
    return plistConfig;
  });
}

function withSceneDelegateFile(config) {
  config = withDangerousMod(config, [
    'ios',
    async (modConfig) => {
      const { platformProjectRoot, projectName } = modConfig.modRequest;
      fs.writeFileSync(path.join(platformProjectRoot, projectName, SCENE_DELEGATE_FILE), SCENE_DELEGATE_SOURCE);
      return modConfig;
    },
  ]);
  return withXcodeProject(config, (projectConfig) => {
    const { projectName } = projectConfig.modRequest;
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!projectConfig.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: projectConfig.modResults,
      });
    }
    return projectConfig;
  });
}

function withAppDelegatePatch(config) {
  return withAppDelegate(config, (delegateConfig) => {
    if (delegateConfig.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate.');
    }
    delegateConfig.modResults.contents = removeTemplateWindowSetup(delegateConfig.modResults.contents);
    return delegateConfig;
  });
}

module.exports = function withSceneLifecycle(config) {
  return withAppDelegatePatch(withSceneDelegateFile(withSceneManifest(config)));
};

module.exports.MARKER = MARKER;
module.exports.SCENE_MANIFEST = SCENE_MANIFEST;
module.exports.SCENE_DELEGATE_SOURCE = SCENE_DELEGATE_SOURCE;
module.exports.removeTemplateWindowSetup = removeTemplateWindowSetup;
